import assert from 'node:assert/strict';
import { wedding, weddingEvents, normalizeEventType, eventLabels, dateLabel, fullDateLabel, timeLabel, eventDate, calendarUrl } from '../app/wedding-config.ts';

assert.equal(dateLabel, '28 November 2026');
assert.equal(fullDateLabel, 'Sabtu, 28 November 2026');
assert.equal(timeLabel, '10.00–13.00 WIB');
assert.equal(eventDate().toISOString(), '2026-11-28T03:00:00.000Z');
const url = new URL(calendarUrl());
assert.equal(url.hostname, 'calendar.google.com');
assert.equal(url.searchParams.get('dates'), '20261128T030000Z/20261128T060000Z');
assert.equal(url.searchParams.get('location'), `${wedding.venueName}, ${wedding.venueAddress}`);
assert.equal(normalizeEventType(undefined), 'pria');
assert.equal(normalizeEventType(''), 'pria');
assert.equal(normalizeEventType(' Wanita '), 'wanita');
assert.equal(normalizeEventType('unknown'), null);
assert.equal(wedding.brideFather, 'Muhammad Bahrodin');
assert.equal(weddingEvents.pria.venueName, 'Kediaman mempelai pria');
assert.equal(weddingEvents.wanita.venueAddress, 'Dsn. Krajan 1, RT 05/RW 06, Setail, Genteng, Banyuwangi (Selatan Ponpes Raudlatut Thalabah)');
assert(weddingEvents.wanita.sessions.every(session => session.venueAddress === weddingEvents.wanita.venueAddress));
assert.equal(eventDate(weddingEvents.wanita).toISOString(), '2026-11-20T01:00:00.000Z');
assert.equal(calendarUrl(weddingEvents.wanita), null);
assert.equal(eventLabels(weddingEvents.wanita).fullDateLabel, 'Jumat, 20 November 2026');
assert.equal(eventLabels(weddingEvents.wanita).timeLabel, '08.00 WIB s/d Selesai');
assert.deepEqual(weddingEvents.wanita.sessions.map(session => session.title), ['Akad Nikah', 'Resepsi']);
assert.equal(eventLabels(weddingEvents.wanita.sessions[1]).timeLabel, '14.00 WIB s/d Selesai');
assert.equal(eventDate(weddingEvents.wanita.sessions[1]).toISOString(), '2026-11-20T07:00:00.000Z');
assert.match(weddingEvents.wanita.mapsEmbedUrl, /-8.3622471%2C114.1318747/);
assert.equal(weddingEvents.wanita.mapsUrl, 'https://maps.app.goo.gl/z6gegTTCZxpLcWF9A?g_st=ic');
const pendingEvent = { ...weddingEvents.wanita, date: null, time: null, endTime: null };
assert.equal(eventDate(pendingEvent), null);
assert.equal(calendarUrl(pendingEvent), null);
assert.equal(eventLabels(pendingEvent).dateLabel, 'Tanggal akan diumumkan');
const otherEvent = { ...weddingEvents.wanita, date: '2026-12-05', time: '09:00', endTime: '12:00', venueAddress: 'Alamat uji acara wanita' };
assert.equal(eventLabels(otherEvent).fullDateLabel, 'Sabtu, 5 Desember 2026');
assert.equal(eventDate(otherEvent).toISOString(), '2026-12-05T02:00:00.000Z');
const otherUrl = new URL(calendarUrl(otherEvent));
assert.equal(otherUrl.searchParams.get('dates'), '20261205T020000Z/20261205T050000Z');
assert.equal(otherUrl.searchParams.get('location'), 'Kediaman mempelai wanita, Alamat uji acara wanita');
assert.equal(calendarUrl({ ...otherEvent, endTime: '08:00' }), null);
console.log('Wedding date and Calendar URL: PASS');
