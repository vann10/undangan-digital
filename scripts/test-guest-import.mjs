import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';

const temp = mkdtempSync(resolve(tmpdir(), 'invitation-import-'));
const pendingTemp = mkdtempSync(resolve(tmpdir(), 'invitation-pending-'));
const script = resolve('scripts/prepare-guests.mjs');
try {
  writeFileSync(resolve(temp, 'guests.json'), JSON.stringify(['Tamu Pertama', 'Tamu Kedua']));
  execFileSync(process.execPath, [script, 'generate', resolve(temp, 'guests.json')], { cwd: temp });
  const guests = readFileSync(resolve(temp, 'data/private/guests.csv'), 'utf8');
  const links = readFileSync(resolve(temp, 'data/private/links.csv'), 'utf8');
  const storedCode = guests.match(/"1","Tamu Pertama","(\d{4})","TRUE"/)?.[1];
  const code = links.match(/\/invite\/1-(\d{4})/)?.[1];
  const secondCode = links.match(/\/invite\/2-(\d{4})/)?.[1];
  assert(storedCode && code && secondCode);
  assert.notEqual(code, secondCode);
  assert.equal(storedCode, code);
  assert.throws(() => execFileSync(process.execPath, [script, 'generate', resolve(temp, 'guests.json'), 'https://example.test'], { cwd: temp, stdio: 'ignore' }));
  copyFileSync(resolve(temp, 'data/private/guests.csv'), resolve(temp, 'data/private/guests-4digit.csv'));
  copyFileSync(resolve(temp, 'data/private/links.csv'), resolve(temp, 'data/private/links-4digit.csv'));
  assert.match(readFileSync(resolve(temp, 'data/private/links-4digit.csv'), 'utf8'), /\/invite\/1-\d{4}/);
  execFileSync(process.execPath, [script, 'add-short', 'Tamu Ketiga'], { cwd: temp });
  const addition = JSON.parse(readFileSync(resolve(temp, 'data/private/new-guest-3.json'), 'utf8'));
  const addedCode = addition.personalPath.match(/^\/invite\/3-(\d{4})$/)?.[1];
  assert(addedCode && addedCode !== code && addedCode !== secondCode);
  assert.equal(addition.fullName, 'Tamu Ketiga');
  assert.equal(addition.guestCode, addedCode);
  assert.throws(() => execFileSync(process.execPath, [script, 'add-short', 'Tamu Ketiga'], { cwd: temp, stdio: 'ignore' }));
  execFileSync(process.execPath, [script, 'add-short', 'Tamu Keempat'], { cwd: temp });
  assert.equal(JSON.parse(readFileSync(resolve(temp, 'data/private/new-guest-4.json'), 'utf8')).invitationId, 4);
  execFileSync(process.execPath, [script, 'reissue', '1', 'https://example.test'], { cwd: temp });
  const reissueFile = readdirSync(resolve(temp, 'data/private')).find(name => /^reissue-1-[a-f0-9]{8}\.txt$/.test(name));
  const reissue = readFileSync(resolve(temp, 'data/private', reissueFile), 'utf8');
  assert.match(reissue, /New URL: https:\/\/example\.test\/invite\/1-\d{4}/);
  assert.match(reissue, /New guest code: \d{4}/);
  writeFileSync(resolve(pendingTemp, 'guests.json'), JSON.stringify(['Tamu Pertama']));
  execFileSync(process.execPath, [script, 'generate', resolve(pendingTemp, 'guests.json')], { cwd: pendingTemp });
  assert.match(readFileSync(resolve(pendingTemp, 'data/private/links.csv'), 'utf8'), /"\/invite\/1-\d{4}"/);
  execFileSync(process.execPath, [script, 'finalize-links', 'https://example.test'], { cwd: pendingTemp });
  assert.match(readFileSync(resolve(pendingTemp, 'data/private/links-final.csv'), 'utf8'), /"https:\/\/example\.test\/invite\/1-\d{4}"/);
  console.log('Guest import: PASS (unique four-digit codes, migration files, new guests, overwrite protection, reissue)');
} finally { rmSync(temp, { recursive: true, force: true }); rmSync(pendingTemp, { recursive: true, force: true }); }
